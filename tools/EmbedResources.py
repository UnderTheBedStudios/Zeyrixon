#!/usr/bin/env python3
"""
Bakes the editor's font and images into the engine as C++ arrays, so a build needs no loose files next to it.

Run from anywhere (needs g++ and Python 3), then commit the generated files:
    python3 tools/EmbedResources.py

Outputs (Zeyrixon/src/Zeyrixon/Embedded/):
    EmbeddedFont.cpp    JetBrainsMono Nerd Font, compressed with ImGui's own tool
    EmbeddedImages.cpp  Icon.png, the content browser icons and the light gizmos, as raw PNG bytes
"""
import subprocess, sys, tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "Zeyrixon" / "src" / "Zeyrixon" / "Embedded"
TOOL_SRC = ROOT / "ZeyrixonEditor" / "vendor" / "imgui" / "misc" / "fonts" / "binary_to_compressed_c.cpp"

FONT = ROOT / "ZeyrixonEditor" / "Assets" / "Fonts" / "JetBrainsMonoNLNerdFont-Regular.ttf"
IMAGES = [
    ("WindowIcon",   ROOT / "Icon.png"),
    ("FolderClosed", ROOT / "Icons" / "ClosedFolder.png"),
    ("FolderOpen",   ROOT / "Icons" / "Folder.png"),
    ("File",         ROOT / "Icons" / "File.png"),
    # Viewport light gizmos (drawn over each Light entity in the editor)
    ("DirectionalLight", ROOT / "ZeyrixonEditor" / "Assets" / "Images" / "DirectionalLight.png"),
    ("PointLight",       ROOT / "ZeyrixonEditor" / "Assets" / "Images" / "PointLight.png"),
    ("SpotLight",        ROOT / "ZeyrixonEditor" / "Assets" / "Images" / "SpotLight.png"),
]

HEADER = "// GENERATED by tools/EmbedResources.py - do not edit by hand.\n#include <pch.h>\n#include <Zeyrixon/Embedded/EmbeddedResources.h>\n\n"


def gen_font():
    with tempfile.TemporaryDirectory() as tmp:
        exe = Path(tmp) / "b2c"
        subprocess.run(["g++", "-O1", "-o", str(exe), str(TOOL_SRC)], check=True)
        out = subprocess.run([str(exe), "-nostatic", str(FONT), "NerdFont"],
                             check=True, capture_output=True, text=True).stdout
    # Drop the tool's comment lines (they contain absolute paths of whoever ran this).
    out = "".join(l for l in out.splitlines(keepends=True) if not l.startswith("//"))
    # The tool emits const globals; the extern declarations in the header give them external linkage.
    (OUT / "EmbeddedFont.cpp").write_text(HEADER + "namespace Zeyrixon::Embedded {\n" + out + "\n}\n")


def gen_images():
    parts = [HEADER, "namespace Zeyrixon::Embedded {\n"]
    for name, path in IMAGES:
        data = path.read_bytes()
        rows = []
        for i in range(0, len(data), 24):
            rows.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        parts.append(f"const unsigned char {name}Png[] = {{\n" + "\n".join(rows) + "\n};\n")
        parts.append(f"const unsigned long long {name}PngSize = {len(data)};\n\n")
    parts.append("}\n")
    (OUT / "EmbeddedImages.cpp").write_text("".join(parts))


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    gen_font()
    gen_images()
    print("Wrote", OUT)
